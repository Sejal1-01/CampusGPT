#!/bin/bash
set -euo pipefail
unset MYSQL_HOST MYSQL_PORT MYSQL_TCP_PORT
mysql -uroot -p"$MYSQL_ROOT_PASSWORD" <<SQL
CREATE DATABASE IF NOT EXISTS campus CHARACTER SET utf8mb4 COLLATE utf8mb4_unicode_ci;
CREATE DATABASE IF NOT EXISTS campus_auth CHARACTER SET utf8mb4 COLLATE utf8mb4_unicode_ci;
CREATE USER IF NOT EXISTS '${MYSQL_RO_USER}'@'%' IDENTIFIED BY '${MYSQL_RO_PASSWORD}';
CREATE USER IF NOT EXISTS '${MYSQL_APP_USER}'@'%' IDENTIFIED BY '${MYSQL_APP_PASSWORD}';
CREATE USER IF NOT EXISTS '${MYSQL_AUTH_RW_USER}'@'%' IDENTIFIED BY '${MYSQL_AUTH_RW_PASSWORD}';
GRANT SELECT ON campus.* TO '${MYSQL_RO_USER}'@'%';
GRANT SELECT ON campus.* TO '${MYSQL_APP_USER}'@'%';
GRANT SELECT ON campus_auth.* TO '${MYSQL_APP_USER}'@'%';
GRANT SELECT, INSERT, UPDATE, DELETE ON campus_auth.* TO '${MYSQL_AUTH_RW_USER}'@'%';
FLUSH PRIVILEGES;
SQL
